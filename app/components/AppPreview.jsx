function PreviewGallery() {
    const [selectedImage, setSelectedImage] = useState(null);

    useEffect(() => {
        if (!selectedImage) return;

        const handleEscape = (event) => {
            if (event.key === "Escape") {
                setSelectedImage(null);
            }
        };

        const previousOverflow = document.body.style.overflow;
        document.body.style.overflow = "hidden";

        window.addEventListener("keydown", handleEscape);

        return () => {
            document.body.style.overflow = previousOverflow;
            window.removeEventListener("keydown", handleEscape);
        };
    }, [selectedImage]);

    return (
        <>
            <div className="grid grid-cols-1 gap-4 md:grid-cols-[minmax(0,1fr)_180px]">


                <button
                    type="button"
                    onClick={() => setSelectedImage(previewImages[0])}
                    className="group aspect-video overflow-hidden rounded-2xl border border-gray-200 bg-gray-50 shadow-lg"
                    aria-label="View free shipping bar preview"
                >
                    <img
                        src={previewImages[0].src}
                        alt="Free Shipping Booster app preview"
                        className="h-full w-full object-cover transition-transform duration-300 group-hover:scale-[1.02]"
                    />
                </button>


                <div className="flex flex-col gap-4">
                    {previewImages.map((image) => (
                        <button
                            key={image.src}
                            type="button"
                            onClick={() => setSelectedImage(image)}
                            className="group aspect-video w-full overflow-hidden rounded-xl border border-gray-200 bg-gray-50"
                            aria-label={`View ${image.alt}`}
                        >
                            <img
                                src={image.src}
                                alt={image.alt}
                                className="h-full w-full object-cover transition-transform duration-300 group-hover:scale-105"
                            />
                        </button>
                    ))}
                </div>
            </div>

            {/* Image Modal */}
            {selectedImage && (
                <div
                    onClick={() => setSelectedImage(null)}
                    className="fixed inset-0 z-[9999] flex items-center justify-center bg-black/90 p-4 backdrop-blur-sm"
                    role="dialog"
                    aria-modal="true"
                    aria-label="Image preview"
                >
                    {/* Close Button */}
                    <button
                        type="button"
                        onClick={() => setSelectedImage(null)}
                        className="absolute right-5 top-5 z-10 flex h-11 w-11 items-center justify-center rounded-full bg-white/15 text-3xl text-white transition hover:bg-white/30"
                        aria-label="Close image preview"
                    >
                        &times;
                    </button>

                    {/* Large Image */}
                    <img
                        src={selectedImage.src}
                        alt={selectedImage.alt}
                        onClick={(event) => event.stopPropagation()}
                        className="max-h-[90vh] max-w-[95vw] rounded-xl object-contain shadow-2xl"
                    />
                </div>
            )}
        </>
    );
}

